using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace CsvHelper.Docs.Snippets;

/// <summary>What one side of a migration guide compiles against: a CsvHelper package, or the projects of the working tree.</summary>
/// <param name="PackageVersion">The version of the CsvHelper package; null for the working tree's src/CsvHelper and its generator.</param>
/// <param name="TargetFramework">The target framework of the project the snippets are compiled in.</param>
internal sealed record SnippetLibrary(string? PackageVersion, string TargetFramework)
{
	/// <summary>The library as the check's output names it.</summary>
	/// <returns><c>CsvHelper 33.1.0</c> or <c>the working tree</c>.</returns>
	public override string ToString() => PackageVersion is null ? "the working tree" : $"CsvHelper {PackageVersion}";
}

/// <summary>
/// Compiles snippets in a generated SDK project, so that restoring the package, the reference assemblies and the source
/// generator all come from the .NET SDK. Each snippet is a file: its using directives at the top, its types in a namespace
/// of its own, its statements in a method. <c>#line</c> directives map errors back to the Markdown file.
/// </summary>
internal static partial class SnippetProject
{
	/// <summary>Writes the project and builds it.</summary>
	/// <param name="repo">The repository.</param>
	/// <param name="directory">The project's folder (under docs/.cache/snippets).</param>
	/// <param name="markdownPath">The full path of the Markdown file of the snippets, which errors refer to.</param>
	/// <param name="library">What the snippets compile against.</param>
	/// <param name="snippets">The snippets.</param>
	/// <returns>The errors (<c>file(line,col): error CSxxxx: message</c>); empty when the snippets compile.</returns>
	public static List<string> Build(string repo, string directory, string markdownPath, SnippetLibrary library, IReadOnlyList<Snippet> snippets)
	{
		Directory.CreateDirectory(directory);
		foreach (var file in Directory.EnumerateFiles(directory, "*.cs"))
		{
			File.Delete(file);
		}

		File.WriteAllText(Path.Combine(directory, "Snippets.csproj"), Project(repo, library));
		File.WriteAllText(Path.Combine(directory, "Prelude.cs"), Prelude);
		foreach (var snippet in snippets)
		{
			File.WriteAllText(Path.Combine(directory, $"Snippet{snippet.Line}.cs"), Wrap(snippet, markdownPath));
		}

		var result = ProcessRunner.Run("dotnet", ["build", "-nologo", "-v:q", "-clp:NoSummary;ErrorsOnly"], directory, TimeSpan.FromMinutes(15));
		var errors = result.Combined.Split('\n')
			.Select(line => ErrorLine().Match(line.Trim()))
			.Where(m => m.Success)
			.Select(m => m.Groups["error"].Value)
			.Distinct()
			.ToList();
		if (result.ExitCode != 0 && errors.Count == 0)
		{
			errors.Add($"the build failed: {result.Combined.Trim()}");
		}

		return errors;
	}

	/// <summary>The project file: the target framework, and the CsvHelper package or the working tree's projects.</summary>
	/// <param name="repo">The repository, for the working tree's projects.</param>
	/// <param name="library">What the snippets compile against.</param>
	/// <returns>The project file's XML.</returns>
	private static string Project(string repo, SnippetLibrary library)
	{
		var reference = library.PackageVersion is { } version
			? $"""<PackageReference Include="CsvHelper" Version="[{version}]" />"""
			: $"""
				<ProjectReference Include="{Path.Combine(repo, "src", "CsvHelper", "CsvHelper.csproj")}" />
				    <ProjectReference Include="{Path.Combine(repo, "src", "CsvHelper.Generators", "CsvHelper.Generators.csproj")}" OutputItemType="Analyzer" ReferenceOutputAssembly="false" />
				""";

		return $"""
			<Project Sdk="Microsoft.NET.Sdk">
			  <!-- Generated by tools/CsvHelper.Docs (check-snippets): the snippets of a migration guide against {library}. -->
			  <PropertyGroup>
			    <TargetFramework>{library.TargetFramework}</TargetFramework>
			    <LangVersion>latest</LangVersion>
			    <Nullable>disable</Nullable>
			    <ImplicitUsings>disable</ImplicitUsings>
			    <NuGetAudit>false</NuGetAudit>
			    <TreatWarningsAsErrors>false</TreatWarningsAsErrors>
			    <NoWarn>$(NoWarn);NU1701;NU1603;CS0105;CS0162;CS0168;CS0169;CS0219;CS0414;CS0649;CS1998;CS8019;CS8632</NoWarn>
			  </PropertyGroup>
			  <ItemGroup>
			    {reference}
			  </ItemGroup>
			</Project>
			""";
	}

	/// <summary>
	/// What every snippet can use without declaring it: the usual namespaces (the old CsvHelper namespaces too, declared
	/// empty here so that they exist in every version), and <c>reader</c>, <c>writer</c>, <c>stream</c>, <c>path</c> and
	/// <c>cancellationToken</c>.
	/// </summary>
	private const string Prelude = """
		global using System;
		global using System.Collections.Generic;
		global using System.Globalization;
		global using System.IO;
		global using System.Linq;
		global using System.Text;
		global using System.Threading;
		global using System.Threading.Tasks;
		global using CsvHelper;
		global using CsvHelper.Configuration;
		global using CsvHelper.Configuration.Attributes;
		global using CsvHelper.TypeConversion;
		global using CsvHelper.Expressions;
		global using static SnippetAmbient;

		namespace CsvHelper.Configuration { internal static class SnippetNamespace { } }
		namespace CsvHelper.Configuration.Attributes { internal static class SnippetNamespace { } }
		namespace CsvHelper.TypeConversion { internal static class SnippetNamespace { } }
		namespace CsvHelper.Expressions { internal static class SnippetNamespace { } }

		#if NETFRAMEWORK
		namespace System.Runtime.CompilerServices { internal static class IsExternalInit { } }
		#endif

		internal static class SnippetAmbient
		{
			public static TextReader reader = TextReader.Null;
			public static TextWriter writer = TextWriter.Null;
			public static Stream stream = Stream.Null;
			public static string path = "file.csv";
			public static CancellationToken cancellationToken = CancellationToken.None;
		}
		""";

	/// <summary>The file of one snippet.</summary>
	/// <param name="snippet">The snippet.</param>
	/// <param name="markdownPath">The full path of its Markdown file, for the <c>#line</c> directives.</param>
	/// <returns>The C# file's text.</returns>
	private static string Wrap(Snippet snippet, string markdownPath)
	{
		var root = (CompilationUnitSyntax)CSharpSyntaxTree.ParseText(snippet.Code, new CSharpParseOptions(LanguageVersion.Preview)).GetRoot();
		var file = new StringBuilder();
		void Append(SyntaxNode node)
		{
			var line = snippet.Line + node.GetLocation().GetLineSpan().StartLinePosition.Line;
			file.AppendLine($"#line {line} \"{markdownPath}\"");
			file.AppendLine(node.ToString());
			file.AppendLine("#line default");
		}

		foreach (var node in root.Usings)
		{
			Append(node);
		}

		foreach (var node in root.AttributeLists)
		{
			Append(node);
		}

		file.AppendLine($"namespace Snippets.L{snippet.Line}");
		file.AppendLine("{");
		foreach (var node in root.Members.Where(m => m is not GlobalStatementSyntax))
		{
			Append(node);
		}

		var statements = root.Members.OfType<GlobalStatementSyntax>().ToList();
		var isAsync = statements.Any(s => s.DescendantTokens().Any(t => t.IsKind(SyntaxKind.AwaitKeyword)));
		file.AppendLine("internal static class SnippetBody");
		file.AppendLine("{");
		file.AppendLine(isAsync ? "internal static async Task Run()" : "internal static void Run()");
		file.AppendLine("{");
		foreach (var node in statements)
		{
			Append(node);
		}

		file.AppendLine("}");
		file.AppendLine("}");
		file.AppendLine("}");

		return file.ToString();
	}

	/// <summary>An error of the compiler or of NuGet, without the project the build appends.</summary>
	[GeneratedRegex(@"^(?<error>.+?: error [A-Z]+\d+: .+?)(?: \[[^\]]+\])?$")]
	private static partial Regex ErrorLine();
}

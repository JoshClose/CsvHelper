using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis.CSharp;

namespace CsvHelper.Generators;

/// <summary>Writes the source of a [CsvRecord] type's mapper, and the module initializer that registers the mappers.</summary>
internal static class RecordEmitter
{
	private static readonly string GeneratedCode =
		$"[global::System.CodeDom.Compiler.GeneratedCode(\"CsvHelper.Generators\", \"{typeof(RecordEmitter).Assembly.GetName().Version}\")]";

	// Ends the messages that leave out a field's value, as the library's own parse errors do.
	private const string HiddenNote = "IncludeValuesInExceptions is off, so its value is not shown";

	/// <summary>
	/// Writes the partial declaration of a [CsvRecord] type that adds its <c>CreateCsvMapper</c> factory and the
	/// nested <c>GeneratedCsvMapper</c> class (the column fields, the constructor that resolves them, <c>Read</c>, and
	/// the parse methods of its enums, null values and booleans), and its <c>CreateCsvWriter</c> factory and the nested
	/// <c>GeneratedCsvWriter</c> class (<c>WriteHeader</c>, <c>Write</c> and the format methods of its enums).
	/// </summary>
	/// <param name="model">The type, as the parser described it; it must have no errors.</param>
	/// <param name="projections">
	/// Whether to also write <c>GetCsvMembers</c>, <c>CreateCsvProjection</c> and the nested <c>Projection</c> mapper that
	/// reads only some members (when the assembly references CsvHelper.Linq or has [assembly: CsvRecordProjections]).
	/// </param>
	/// <returns>The C# source of the file.</returns>
	public static string Emit(RecordModel model, bool projections)
	{
		var w = new CodeWriter();
		w.Line("// <auto-generated/>");
		w.Line("#nullable enable");
		w.Line("#pragma warning disable CS0612, CS0618 // members may be obsolete");
		w.Line();
		if (model.Namespace is not null) w.Open($"namespace {model.Namespace}");
		foreach (var container in model.Containers) w.Open(container);
		w.Open(model.Declaration);
		w.Line($"/// <summary>Creates the mapper that reads <c>{model.Name}</c> records with the columns of <paramref name=\"reader\"/> (generated for [CsvRecord]).</summary>");
		w.Line("[global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]");
		w.Line($"internal static global::CsvHelper.CsvRecordMapper<{model.FullName}> CreateCsvMapper(global::CsvHelper.CsvReader reader, string columnPrefix) => new GeneratedCsvMapper(reader, columnPrefix);");
		w.Line();
		w.Line($"/// <summary>Creates the record writer that writes <c>{model.Name}</c> records with <paramref name=\"columnPrefix\"/> in front of the column names (generated for [CsvRecord]).</summary>");
		w.Line("[global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]");
		var writer = model.Writer;
		if (writer.Problem is { } problem)
		{
			var message = Quote($"Records of {model.Name} cannot be written: {problem}.");
			w.Line($"internal static global::CsvHelper.CsvRecordWriter<{model.FullName}> CreateCsvWriter(string columnPrefix) => throw new global::System.InvalidOperationException({message});");
		}
		else
		{
			w.Line($"internal static global::CsvHelper.CsvRecordWriter<{model.FullName}> CreateCsvWriter(string columnPrefix) => new GeneratedCsvWriter(columnPrefix);");
		}

		if (model.Options is { } options)
		{
			EmitOptions(w, model.Name, "CsvReaderOptions", options.Reader);
			EmitOptions(w, model.Name, "CsvWriterOptions", options.Writer);
		}

		if (projections)
		{
			EmitMembers(w, model);
		}

		w.Line();
		w.Line(GeneratedCode);
		w.Open($"private sealed class GeneratedCsvMapper : global::CsvHelper.CsvRecordMapper<{model.FullName}>");
		EmitFields(w, model, false);
		EmitConstructor(w, model);
		EmitRead(w, model);
		if (model.Refillable) EmitRefill(w, model);
		EmitFindFailingMember(w, model, false);
		foreach (var c in model.Collections) EmitCollection(w, c);
		foreach (var v in model.Validators) EmitValidator(w, v);
		foreach (var e in model.Enums) EmitEnumParser(w, e);
		foreach (var m in model.NullMatchers) EmitNullMatcher(w, m);
		foreach (var b in model.Booleans) EmitBooleanParser(w, b);
		if (projections)
		{
			EmitProjection(w, model);
		}

		w.Close();
		if (writer.Problem is null)
		{
			EmitWriter(w, model);
		}

		w.Close();
		foreach (var _ in model.Containers) w.Close();
		if (model.Namespace is not null) w.Close();

		return w.ToString();
	}

	/// <summary>
	/// Writes the module initializer that registers the mappers of the assembly with <c>CsvRecordMapper.Register</c>
	/// when it is loaded.
	/// </summary>
	/// <param name="registrations">The mappers to register, in the order to write them.</param>
	/// <param name="polyfill">
	/// Whether the compilation lacks <c>ModuleInitializerAttribute</c>, so that the file declares it too.
	/// </param>
	/// <returns>The C# source of the file.</returns>
	public static string EmitRegistrations(IEnumerable<RegistrationModel> registrations, bool polyfill)
	{
		var w = new CodeWriter();
		w.Line("// <auto-generated/>");
		w.Line("#pragma warning disable CA2255 // registers this assembly's [CsvRecord] mappers with CsvHelper");
		w.Line();
		if (polyfill)
		{
			w.Open("namespace System.Runtime.CompilerServices");
			w.Line("[global::System.AttributeUsage(global::System.AttributeTargets.Method, Inherited = false)]");
			w.Open("internal sealed class ModuleInitializerAttribute : global::System.Attribute");
			w.Close();
			w.Close();
			w.Line();
		}

		w.Open("namespace CsvHelper.Generated");
		w.Line("/// <summary>Registers the mappers of this assembly's [CsvRecord] types when the assembly is loaded.</summary>");
		w.Line(GeneratedCode);
		w.Open("internal static class CsvRecordRegistrations");
		w.Line("[global::System.Runtime.CompilerServices.ModuleInitializer]");
		w.Open("internal static void Register()");
		foreach (var r in registrations)
		{
			var widths = r.FieldWidths.Length == 0
				? ""
				: ", new int[] { " + string.Join(", ", r.FieldWidths.Select(n => n.ToString(CultureInfo.InvariantCulture))) + " }";
			if (r.ProjectionHost is { } projectionHost)
			{
				var layout = widths.Length == 0 ? ", null" : widths;
				w.Line($"global::CsvHelper.CsvRecordMapper.Register<{r.FullName}>({r.Factory}{layout}, {projectionHost}.GetCsvMembers, {projectionHost}.CreateCsvProjection);");
			}
			else
			{
				w.Line($"global::CsvHelper.CsvRecordMapper.Register<{r.FullName}>({r.Factory}{widths});");
			}

			if (r.WriterFactory is not null)
			{
				w.Line($"global::CsvHelper.CsvRecordWriter.Register<{r.FullName}>({r.WriterFactory});");
			}

			if (r.OptionsHost is not null)
			{
				w.Line($"global::CsvHelper.CsvRecordMapper.RegisterOptions<{r.FullName}>({r.OptionsHost}.CreateCsvReaderOptions, {r.OptionsHost}.CreateCsvWriterOptions);");
			}
		}

		w.Close();
		w.Close();
		w.Close();

		return w.ToString();
	}

	/// <summary>Writes the method that creates the reader or writer options of the type's [CsvOptions].</summary>
	private static void EmitOptions(CodeWriter w, string name, string optionsType, EquatableArray<string> assignments)
	{
		w.Line();
		w.Line($"/// <summary>Creates the {(optionsType == "CsvReaderOptions" ? "reader" : "writer")} options of the [CsvOptions] of <c>{name}</c> (generated).</summary>");
		w.Line("[global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]");
		var create = optionsType == "CsvReaderOptions" ? "CreateCsvReaderOptions" : "CreateCsvWriterOptions";
		w.Line($"internal static global::CsvHelper.{optionsType} {create}() => new global::CsvHelper.{optionsType} {{ {string.Join(", ", assignments)} }};");
	}

	/// <summary>
	/// Writes the fields of a mapper: its columns, collection columns, format providers, converters and nested mappers;
	/// the static format arrays only in <c>GeneratedCsvMapper</c>, whose <c>Projection</c> uses them too, and the
	/// <c>select</c> flags of the members only in the projection.
	/// </summary>
	private static void EmitFields(CodeWriter w, RecordModel model, bool projection)
	{
		for (var i = 0; i < model.Columns.Length; i++) w.Line($"private readonly int {Field(i)};");
		foreach (var c in model.Collections.Where(c => c.Field is not null))
			w.Line(c.Kind == "dictionary" ? $"private readonly string[] {c.Field};" : $"private readonly int[] {c.Field};");
		if (model.NeedsProvider) w.Line("private readonly global::System.IFormatProvider provider;");
		foreach (var c in model.Cultures) w.Line($"private readonly global::System.IFormatProvider {c.Field};");
		foreach (var c in model.Converters) w.Line($"private readonly {c.Type} {c.Field} = new {c.Type}();");
		foreach (var n in model.Nested) w.Line($"private readonly global::CsvHelper.CsvRecordMapper<{n.Type}> {n.Field};");
		if (projection)
		{
			for (var i = 0; i < model.Members.Length; i++)
			{
				w.Line($"private readonly bool {Select(i)};");
			}
		}
		else
		{
			foreach (var f in model.FormatArrays)
			{
				w.Line($"private static readonly string[] {f.Field} = new string[] {{ {string.Join(", ", f.Formats.Select(Quote))} }};");
			}
		}

		if (model.Columns.Length > 0 || model.Collections.Any(c => c.Field is not null) || model.NeedsProvider || model.Cultures.Length > 0 ||
			model.Converters.Length > 0 || model.Nested.Length > 0 || (projection ? model.Members.Length > 0 : model.FormatArrays.Length > 0)) w.Line();
	}

	/// <summary>
	/// Writes <c>GetCsvMembers</c>, which describes the members that the mapper reads, and <c>CreateCsvProjection</c>,
	/// which creates the mapper that reads only some of them, for <c>CsvRecordMapper.Register</c>.
	/// </summary>
	private static void EmitMembers(CodeWriter w, RecordModel model)
	{
		w.Line();
		w.Line($"/// <summary>Describes the members of <c>{model.Name}</c> that its mapper reads, in the order projections select them (generated for [CsvRecord]).</summary>");
		w.Line("[global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]");
		w.Open("internal static global::System.Collections.Generic.IReadOnlyList<global::CsvHelper.CsvRecordMember> GetCsvMembers() => new global::CsvHelper.CsvRecordMember[]");
		foreach (var m in model.Members)
		{
			var names = m.ColumnNames.Length == 0 ? "new string[0]" : "new string[] { " + string.Join(", ", m.ColumnNames.Select(Quote)) + " }";
			var index = m.Index.ToString(CultureInfo.InvariantCulture);
			var optional = m.Optional ? "true" : "false";
			var parameter = m.Parameter ? "true" : "false";
			w.Line($"new global::CsvHelper.CsvRecordMember({Quote(m.Name)}, typeof({m.Type}), global::CsvHelper.CsvRecordMemberKind.{m.Kind}, {names}, {index}, {optional}, {parameter}),");
		}

		w.Unindent();
		w.Line("};");
		w.Line();
		w.Line($"/// <summary>Creates the mapper that reads only the selected members of <c>{model.Name}</c> with the columns of <paramref name=\"reader\"/> (generated for [CsvRecord]).</summary>");
		w.Line("[global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]");
		w.Line($"internal static global::CsvHelper.CsvRecordMapper<{model.FullName}> CreateCsvProjection(global::CsvHelper.CsvReader reader, string columnPrefix, bool[] selected) => new GeneratedCsvMapper.Projection(reader, columnPrefix, selected);");
	}

	/// <summary>
	/// Writes the nested <c>Projection</c> class, a mapper that resolves and reads only the selected members: the others
	/// get their defaults (constructor parameters their default values) or keep their own initial values, their columns
	/// may be missing, and their [CsvValidate] checks do not run. It has the fields and collection methods of
	/// <c>GeneratedCsvMapper</c>, and uses its static helpers, so the read expressions are the same.
	/// </summary>
	private static void EmitProjection(CodeWriter w, RecordModel model)
	{
		w.Line();
		w.Line($"/// <summary>Reads the selected members of <c>{model.Name}</c> (generated for [CsvRecord]).</summary>");
		w.Line(GeneratedCode);
		w.Open($"internal sealed class Projection : global::CsvHelper.CsvRecordMapper<{model.FullName}>");
		EmitFields(w, model, true);

		w.Line("public Projection(global::CsvHelper.CsvReader reader, string columnPrefix, bool[] selected)");
		w.Indent();
		w.Line(": base(columnPrefix)");
		w.Unindent();
		w.Line("{");
		w.Indent();
		for (var i = 0; i < model.Members.Length; i++)
		{
			w.Line($"{Select(i)} = selected[{i.ToString(CultureInfo.InvariantCulture)}];");
		}

		for (var i = 0; i < model.Columns.Length; i++)
		{
			w.Line($"{Field(i)} = {Select(model.Columns[i].Owner)} ? {ColumnLookup(model.Columns[i])} : -1;");
		}

		foreach (var c in model.Collections.Where(c => c.Field is not null))
		{
			var empty = c.Kind == "dictionary" ? "new string[0]" : "new int[0]";
			w.Line($"{c.Field} = {Select(c.Owner)} ? {CollectionLookup(c)} : {empty};");
		}

		foreach (var n in model.Nested)
		{
			var selectedBy = string.Join(" || ", n.Owners.Select(Select));
			w.Line($"{n.Field} = {selectedBy} ? NestedMapper<{n.Type}>(reader, {Quote(n.Prefix)}) : null!;");
		}

		w.Line("ThrowIfColumnsMissing(reader);");
		if (model.NeedsProvider)
		{
			w.Line("provider = reader.Options.FormatProvider ?? global::System.Globalization.CultureInfo.InvariantCulture;");
		}

		foreach (var c in model.Cultures)
		{
			w.Line($"{c.Field} = global::System.Globalization.CultureInfo.GetCultureInfo({Quote(c.Name)});");
		}

		w.Close();
		w.Line();

		w.Open($"public override {model.FullName} Read(global::CsvHelper.CsvReader reader)");
		var start = $"var result = new {model.FullName}(";
		var initialized = model.Initializers.Where(a => a.MustInitialize).ToList();
		var end = initialized.Count == 0 ? ";" : "";
		if (model.Arguments.Length == 0)
		{
			w.Line(start + ")" + end);
		}
		else
		{
			w.Line(start);
			w.Indent();
			for (var i = 0; i < model.Arguments.Length; i++)
			{
				var a = model.Arguments[i];
				w.Line($"{Select(a.Owner)} ? ({a.Value}) : {a.Fallback}" + (i < model.Arguments.Length - 1 ? "," : ")" + end));
			}

			w.Unindent();
		}

		if (initialized.Count > 0)
		{
			w.Line("{");
			w.Indent();
			foreach (var a in initialized)
			{
				w.Line($"{a.Member} = {Select(a.Owner)} ? ({a.Value}) : default!,");
			}

			w.Unindent();
			w.Line("};");
		}

		// The other members keep their own initial values when they are not selected.
		foreach (var a in model.Initializers.Where(a => !a.MustInitialize))
		{
			w.Line($"if ({Select(a.Owner)}) result.{a.Member} = {a.Value};");
		}

		// An optional member's column is -1 when it is not selected, as when the header lacks it.
		foreach (var a in model.Assignments)
		{
			w.Line($"if ({Field(a.Column)} >= 0) result.{a.Member} = {a.Value};");
		}

		w.Line();
		w.Line("return result;");
		w.Close();

		EmitFindFailingMember(w, model, true);
		foreach (var c in model.Collections)
		{
			EmitCollection(w, c);
		}

		w.Close();
	}

	/// <summary>The call that finds a column in the constructor of a mapper.</summary>
	private static string ColumnLookup(ColumnModel c)
	{
		// A column that is not the first with its name needs the overload that takes the name index.
		var names = c.AlternateNames.Length == 0 && c.NameIndex == 0
			? Quote(c.Name)
			: "new string[] { " + string.Join(", ", new[] { c.Name }.Concat(c.AlternateNames).Select(Quote)) + " }";
		var nameIndex = c.NameIndex == 0 ? "" : c.NameIndex.ToString(CultureInfo.InvariantCulture) + ", ";

		return $"Column(reader, {names}, {nameIndex}{c.Index.ToString(CultureInfo.InvariantCulture)}, {(c.Optional ? "true" : "false")}, {Quote(c.Member)})";
	}

	/// <summary>The call that finds the columns (or the keys) of a collection member in the constructor of a mapper.</summary>
	private static string CollectionLookup(CollectionModel c)
	{
		var start = c.Start.ToString(CultureInfo.InvariantCulture);
		var end = c.End.ToString(CultureInfo.InvariantCulture);

		return c.Kind == "dictionary"
			? $"ColumnNames(reader, {start}, {end}, {Quote(c.Member)})"
			: $"Columns(reader, new string[] {{ {string.Join(", ", c.Names.Select(Quote))} }}, {(c.Optional ? "true" : "false")}, {Quote(c.Member)})";
	}

	private static void EmitConstructor(CodeWriter w, RecordModel model)
	{
		w.Line("public GeneratedCsvMapper(global::CsvHelper.CsvReader reader, string columnPrefix)");
		w.Indent();
		w.Line(": base(columnPrefix)");
		w.Unindent();
		w.Line("{");
		w.Indent();
		for (var i = 0; i < model.Columns.Length; i++)
		{
			w.Line($"{Field(i)} = {ColumnLookup(model.Columns[i])};");
		}

		foreach (var c in model.Collections.Where(c => c.Field is not null))
		{
			w.Line($"{c.Field} = {CollectionLookup(c)};");
		}

		foreach (var n in model.Nested) w.Line($"{n.Field} = NestedMapper<{n.Type}>(reader, {Quote(n.Prefix)});");
		w.Line("ThrowIfColumnsMissing(reader);");
		if (model.NeedsProvider)
			w.Line("provider = reader.Options.FormatProvider ?? global::System.Globalization.CultureInfo.InvariantCulture;");
		foreach (var c in model.Cultures) w.Line($"{c.Field} = global::System.Globalization.CultureInfo.GetCultureInfo({Quote(c.Name)});");
		w.Close();
		w.Line();
	}

	private static void EmitRead(CodeWriter w, RecordModel model)
	{
		w.Open($"public override {model.FullName} Read(global::CsvHelper.CsvReader reader)");
		var assign = model.Assignments.Length > 0;
		var start = (assign ? "var result = " : "return ") + $"new {model.FullName}(";
		var end = model.Initializers.Length == 0 ? ";" : "";
		if (model.Arguments.Length == 0)
		{
			w.Line(start + ")" + end);
		}
		else
		{
			w.Line(start);
			w.Indent();
			for (var i = 0; i < model.Arguments.Length; i++)
				w.Line(model.Arguments[i].Value + (i < model.Arguments.Length - 1 ? "," : ")" + end));
			w.Unindent();
		}

		if (model.Initializers.Length > 0)
		{
			w.Line("{");
			w.Indent();
			foreach (var a in model.Initializers) w.Line($"{a.Member} = {a.Value},");
			w.Unindent();
			w.Line("};");
		}

		if (assign)
		{
			foreach (var a in model.Assignments) w.Line($"if ({Field(a.Column)} >= 0) result.{a.Member} = {a.Value};");
			w.Line();
			w.Line("return result;");
		}

		w.Close();
	}

	/// <summary>
	/// Writes <c>Read(reader, record)</c>, which sets the members of an existing instance as <c>Read(reader)</c> sets those
	/// of a new one, for <c>EnumerateRecords</c>.
	/// </summary>
	private static void EmitRefill(CodeWriter w, RecordModel model)
	{
		w.Line();
		w.Open($"public override void Read(global::CsvHelper.CsvReader reader, {model.FullName} record)");
		foreach (var a in model.Initializers) w.Line($"record.{a.Member} = {a.Value};");
		foreach (var a in model.Assignments) w.Line($"if ({Field(a.Column)} >= 0) record.{a.Member} = {a.Value};");
		w.Close();
	}

	/// <summary>
	/// Writes <c>FindFailingMember</c>, which reads each member again on its own, in the order <c>Read</c> reads them, and
	/// returns the first that throws, with its field: a nested record asks its own mapper, a collection tries each field.
	/// It runs only after a record failed, so <c>Read</c> stays as it is. A projection reads only its selected members.
	/// </summary>
	private static void EmitFindFailingMember(CodeWriter w, RecordModel model, bool projection)
	{
		w.Line();
		w.Open("public override string? FindFailingMember(global::CsvHelper.CsvReader reader, out int fieldIndex)");
		foreach (var step in model.Steps)
		{
			if (projection)
			{
				w.Open($"if ({Select(step.Owner)})");
				EmitStep(w, step);
				w.Close();
			}
			else
			{
				EmitStep(w, step);
			}
		}

		w.Line("fieldIndex = -1;");
		w.Line();
		w.Line("return null;");
		w.Close();
	}

	/// <summary>Writes the statements of <c>FindFailingMember</c> that read one member again.</summary>
	private static void EmitStep(CodeWriter w, StepModel step)
	{
		var member = Quote(step.Member);
		if (step.Nested is not null)
		{
			w.Open("try");
			w.Line($"_ = {step.Value};");
			w.Continue("catch");
			w.Line($"return {step.Nested}.FindFailingMember(reader, out fieldIndex) ?? {member};");
			w.Close();

			return;
		}

		if (step.Finder is not null)
		{
			w.Open($"if ({step.Finder}(reader, out fieldIndex))");
			w.Line($"return {member};");
			w.Close();
			if (step.Value is not null)
			{
				// The check of the whole collection.
				w.Open("try");
				w.Line($"_ = {step.Value};");
				w.Continue("catch");
				w.Line($"return {member};");
				w.Close();
			}

			return;
		}

		// An optional column that the header lacks is not read.
		w.Open($"if ({Field(step.Column)} >= 0)");
		w.Line($"fieldIndex = {Field(step.Column)};");
		w.Open("try");
		w.Line($"_ = {step.Value};");
		w.Continue("catch");
		w.Line($"return {member};");
		w.Close();
		w.Close();
	}

	/// <summary>
	/// Writes the method that reads a collection member, field by field, and the one that finds the field that fails
	/// (<c>Find</c> in front of its name), for <c>FindFailingMember</c>.
	/// </summary>
	private static void EmitCollection(CodeWriter w, CollectionModel c)
	{
		w.Line();
		w.Open($"private {c.Type} {c.Method}(global::CsvHelper.CsvReader reader)");
		var count = EmitCollectionLoop(w, c);
		if (c.Kind == "dictionary")
		{
			w.Line($"var values = new global::System.Collections.Generic.Dictionary<string, {c.Element}>({count});");
		}
		else if (c.Kind == "list")
		{
			w.Line($"var values = new global::System.Collections.Generic.List<{c.Element}>({count});");
		}
		else
		{
			w.Line($"var values = new {ArrayOf(c.Element, count)};");
		}

		w.Open($"for (var k = 0; k < {count}; k++)");
		w.Line(Index(c));
		if (c.Kind == "dictionary")
		{
			// The first column with a name wins, as in the header lookups.
			w.Open($"if (!values.ContainsKey({c.Field}[k]))");
			w.Line($"values.Add({c.Field}[k], {c.Value});");
			w.Close();
		}
		else
		{
			w.Line(c.Kind == "list" ? $"values.Add({c.Value});" : $"values[k] = {c.Value};");
		}

		w.Close();
		w.Line("return values;");
		w.Close();

		w.Line();
		w.Open($"private bool Find{c.Method}(global::CsvHelper.CsvReader reader, out int fieldIndex)");
		count = EmitCollectionLoop(w, c);
		w.Open($"for (var k = 0; k < {count}; k++)");
		w.Line(Index(c));
		w.Line("fieldIndex = i;");
		w.Open("try");
		w.Line($"_ = {c.Value};");
		w.Continue("catch");
		w.Line("return true;");
		w.Close();
		w.Close();
		w.Line("fieldIndex = -1;");
		w.Line();
		w.Line("return false;");
		w.Close();
	}

	/// <summary>
	/// Writes what the loop over a collection's fields needs (the number of fields of a range that runs to the end of the
	/// record) and returns the expression of the number of fields.
	/// </summary>
	private static string EmitCollectionLoop(CodeWriter w, CollectionModel c)
	{
		if (c.Field is not null)
		{
			return $"{c.Field}.Length";
		}

		var start = c.Start.ToString(CultureInfo.InvariantCulture);
		if (c.End >= 0)
		{
			return (c.End - c.Start + 1).ToString(CultureInfo.InvariantCulture);
		}

		w.Line($"var count = global::System.Math.Max(reader.FieldCount - {start}, 0);");

		return "count";
	}

	/// <summary>The statement that sets <c>i</c>, the field of the <c>k</c>-th element of a collection.</summary>
	private static string Index(CollectionModel c) =>
		c.Kind != "dictionary" && c.Field is not null ? $"var i = {c.Field}[k];" : $"var i = {c.Start.ToString(CultureInfo.InvariantCulture)} + k;";

	/// <summary>The creation of an array of <paramref name="count"/> elements, such as <c>int[count]</c> or <c>int?[count]</c>.</summary>
	private static string ArrayOf(string element, string count) => $"{element}[{count}]";

	/// <summary>
	/// Writes the method that passes a member's value to the check of its [CsvValidate] and returns it, or throws a
	/// <c>CsvValidationException</c>.
	/// </summary>
	private static void EmitValidator(CodeWriter w, ValidatorModel v)
	{
		w.Line();
		w.Open($"private static {v.Type} {v.Method}(global::CsvHelper.CsvReader reader, {v.Type} value)");
		w.Open($"if ({v.Check}(value!))");
		w.Line("return value;");
		w.Close();
		if (v.Message is not null)
		{
			w.Line($"throw new global::CsvHelper.CsvValidationException({Quote(v.Message)});");
		}
		else
		{
			w.Line("throw new global::CsvHelper.CsvValidationException(reader.Options.IncludeValuesInExceptions");
			w.Indent();
			w.Line($"? \"'\" + value + {Quote($"' is not valid for {v.Member}.")}");
			w.Line($": {Quote($"The field is not valid for {v.Member} ({HiddenNote}).")});");
			w.Unindent();
		}

		w.Close();
	}

	/// <summary>
	/// Writes the nested <c>GeneratedCsvWriter</c> class: the fields of its converters, cultures and nested record
	/// writers, the constructor that creates them, <c>FieldCount</c>, <c>WriteHeader</c>, <c>Write</c> and the format
	/// methods of its enums.
	/// </summary>
	private static void EmitWriter(CodeWriter w, RecordModel model)
	{
		var writer = model.Writer;
		w.Line();
		w.Line(GeneratedCode);
		w.Open($"private sealed class GeneratedCsvWriter : global::CsvHelper.CsvRecordWriter<{model.FullName}>");
		foreach (var c in writer.Cultures) w.Line($"private readonly global::System.IFormatProvider {c.Field};");
		foreach (var c in model.Converters) w.Line($"private readonly {c.Type} {c.Field} = new {c.Type}();");
		foreach (var n in model.Nested) w.Line($"private readonly global::CsvHelper.CsvRecordWriter<{n.Type}> {n.Field};");
		var nestedColumns = writer.Columns.Where(c => c.Nested is not null).ToList();
		var ownColumns = (writer.Columns.Length - nestedColumns.Count).ToString(CultureInfo.InvariantCulture);
		if (nestedColumns.Count > 0) w.Line("private readonly int fieldCount;");
		if (writer.Cultures.Length > 0 || model.Converters.Length > 0 || model.Nested.Length > 0) w.Line();

		w.Line("public GeneratedCsvWriter(string columnPrefix)");
		w.Indent();
		w.Line(": base(columnPrefix)");
		w.Unindent();
		w.Line("{");
		w.Indent();
		foreach (var n in model.Nested) w.Line($"{n.Field} = NestedWriter<{n.Type}>({Quote(n.Prefix)});");
		foreach (var c in writer.Cultures) w.Line($"{c.Field} = global::System.Globalization.CultureInfo.GetCultureInfo({Quote(c.Name)});");
		if (nestedColumns.Count > 0) w.Line($"fieldCount = {string.Join(" + ", new[] { ownColumns }.Concat(nestedColumns.Select(c => c.Nested + ".FieldCount")))};");
		w.Close();
		w.Line();

		w.Line($"public override int FieldCount => {(nestedColumns.Count > 0 ? "fieldCount" : ownColumns)};");
		w.Line();

		w.Open("public override void WriteHeader(global::CsvHelper.CsvWriter writer)");
		foreach (var c in writer.Columns) w.Line(c.Nested is not null ? $"{c.Nested}.WriteHeader(writer);" : $"WriteColumnName(writer, {Quote(c.Name ?? "")});");
		w.Close();
		w.Line();

		w.Open($"public override void Write(global::CsvHelper.CsvWriter writer, {model.FullName} record)");
		foreach (var c in writer.Columns)
		{
			foreach (var line in c.Lines) w.Line(line);
		}

		w.Close();
		foreach (var e in writer.Enums) EmitEnumFormatter(w, e);
		w.Close();
	}

	/// <summary>Writes the method that returns the text of an enum value: the name of its member, else <c>ToString()</c>.</summary>
	private static void EmitEnumFormatter(CodeWriter w, EnumFormatModel e)
	{
		w.Line();
		w.Open($"private static string {e.Method}({e.Type} value)");
		if (e.Cases.Length > 0)
		{
			w.Open("switch (value)");
			foreach (var c in e.Cases) w.Line($"case {e.Type}.{Escape(c.Member)}: return {Quote(c.Text)};");
			w.Close();
		}

		w.Line("return value.ToString();");
		w.Close();
	}

	/// <summary>
	/// Matches the UTF-8 bytes of the field against the enum's names (ignoring ASCII case unless two names of
	/// different members differ only in case) and leaves anything else, such as numbers and flag combinations, to
	/// <c>Enum.TryParse</c>.
	/// </summary>
	private static void EmitEnumParser(CodeWriter w, EnumModel e)
	{
		var names = e.Names.Select(n => (Bytes: Encoding.UTF8.GetBytes(n.Text), Result: $"{e.Type}.{Escape(n.Member)}")).ToList();
		w.Line();
		w.Open($"private static {e.Type} {e.Method}(global::CsvHelper.CsvReader reader, int column)");
		w.Line("var s = reader.GetSpan(column);");
		EmitMatch(w, names, Exact(names));
		w.Line($"return {e.Method}(reader.GetString(column), reader.Options.IncludeValuesInExceptions);");
		w.Close();
		w.Line();
		w.Open($"private static {e.Type} {e.Method}(string text, bool showValue)");
		w.Line($"if (global::System.Enum.TryParse<{e.Type}>(text, true, out var value)) return value;");
		w.Line($"throw new global::System.FormatException(showValue ? \"'\" + text + {Quote($"' is not a value of {e.DisplayName}.")} : {Quote($"The field is not a value of {e.DisplayName} ({HiddenNote}).")});");
		w.Close();
	}

	/// <summary>Tells whether a field is exactly one of the [CsvNullValues] of a member.</summary>
	private static void EmitNullMatcher(CodeWriter w, NullMatcherModel m)
	{
		w.Line();
		w.Open($"private static bool {m.Method}(global::System.ReadOnlySpan<byte> s)");
		EmitMatch(w, m.Values.Select(v => (Encoding.UTF8.GetBytes(v), "true")).ToList(), exact: true);
		w.Line("return false;");
		w.Close();
	}

	/// <summary>
	/// Parses a field as one of the [CsvBooleanValues] of a member, ignoring surrounding spaces and tabs, and ASCII
	/// case unless a true and a false value differ only in case.
	/// </summary>
	private static void EmitBooleanParser(CodeWriter w, BooleanModel b)
	{
		var values = b.TrueValues.Select(v => (Bytes: Encoding.UTF8.GetBytes(v), Result: "true"))
			.Concat(b.FalseValues.Select(v => (Bytes: Encoding.UTF8.GetBytes(v), Result: "false")))
			.ToList();
		var all = b.TrueValues.Concat(b.FalseValues).ToList();
		var expected = all.Count == 1 ? all[0] : string.Join(", ", all.Take(all.Count - 1)) + " or " + all[all.Count - 1];
		w.Line();
		w.Open($"private static bool {b.Method}(global::CsvHelper.CsvReader reader, int column)");
		w.Line("var s = reader.GetSpan(column);");
		w.Line("while (s.Length > 0 && (s[0] == 0x20 || s[0] == 0x09)) s = s.Slice(1);");
		w.Line("while (s.Length > 0 && (s[s.Length - 1] == 0x20 || s[s.Length - 1] == 0x09)) s = s.Slice(0, s.Length - 1);");
		EmitMatch(w, values, Exact(values));
		w.Line("throw new global::System.FormatException(reader.Options.IncludeValuesInExceptions");
		w.Indent();
		w.Line($"? \"'\" + reader.GetString(column) + {Quote($"' is not a valid boolean. Expected {expected}.")}");
		w.Line($": {Quote($"The field is not a valid boolean ({HiddenNote}). Expected {expected}.")});");
		w.Unindent();
		w.Close();
	}

	/// <summary>
	/// Writes a switch on the length of the span <c>s</c> that returns the result of the value whose bytes it has, if
	/// any, followed by a blank line.
	/// </summary>
	private static void EmitMatch(CodeWriter w, List<(byte[] Bytes, string Result)> values, bool exact)
	{
		if (values.Count == 0) return;
		w.Open("switch (s.Length)");
		foreach (var group in values.GroupBy(v => v.Bytes.Length).OrderBy(g => g.Key))
		{
			w.Line($"case {group.Key.ToString(CultureInfo.InvariantCulture)}:");
			w.Indent();
			// Only one value is empty: a condition of true would make the break unreachable.
			if (group.Key == 0)
			{
				w.Line($"return {group.First().Result};");
				w.Unindent();
				continue;
			}

			var seen = new HashSet<string>();
			foreach (var (bytes, result) in group)
			{
				var condition = string.Join(" && ", bytes.Select((b, i) => Match(b, i, exact)));
				if (seen.Add(condition)) w.Line($"if ({condition}) return {result};");
			}

			w.Line("break;");
			w.Unindent();
		}

		w.Close();
		w.Line();
	}

	// Whether values must be matched exactly because two of them with different results differ only in ASCII case.
	private static bool Exact(List<(byte[] Bytes, string Result)> values) =>
		values.GroupBy(v => FoldAscii(v.Bytes)).Any(g => g.Select(v => v.Result).Distinct().Count() > 1);

	private static string Match(byte b, int i, bool exact)
	{
		var index = i.ToString(CultureInfo.InvariantCulture);
		var letter = (b | 0x20) is >= 'a' and <= 'z';

		return !exact && letter
			? $"(s[{index}] | 0x20) == 0x{(b | 0x20).ToString("X2", CultureInfo.InvariantCulture)}"
			: $"s[{index}] == 0x{b.ToString("X2", CultureInfo.InvariantCulture)}";
	}

	private static string FoldAscii(byte[] bytes) =>
		new(bytes.Select(b => (char)((b | 0x20) is >= 'a' and <= 'z' ? b | 0x20 : b)).ToArray());

	private static string Field(int column) => "column" + column.ToString(CultureInfo.InvariantCulture);

	private static string Select(int member) => "select" + member.ToString(CultureInfo.InvariantCulture);

	private static string Quote(string text) => SymbolDisplay.FormatLiteral(text, quote: true);

	private static string Escape(string name) => SyntaxFacts.GetKeywordKind(name) != SyntaxKind.None ? "@" + name : name;

	/// <summary>Writes indented lines, with a blank line after each closing brace that more code follows.</summary>
	private sealed class CodeWriter
	{
		private readonly StringBuilder text = new();
		private int depth;
		private bool closed;

		/// <summary>
		/// Writes a line at the current indentation, after a blank line when it follows a closing brace and is not one
		/// itself.
		/// </summary>
		/// <param name="line">The text of the line; <c>""</c> (the default) writes a blank line.</param>
		public void Line(string line = "")
		{
			// A closing brace on its own line is followed by a blank line, unless another one follows.
			if (closed && line.Length > 0 && line != "}") text.AppendLine();
			closed = false;
			if (line.Length > 0) text.Append('\t', depth).Append(line);
			text.AppendLine();
		}

		/// <summary>Writes <paramref name="line"/> and an opening brace, and indents the lines after them.</summary>
		/// <param name="line">The declaration or statement that the block belongs to.</param>
		public void Open(string line)
		{
			Line(line);
			Line("{");
			depth++;
		}

		/// <summary>Ends the indentation of <see cref="Open"/> and writes the closing brace.</summary>
		public void Close()
		{
			depth--;
			Line("}");
			closed = true;
		}

		/// <summary>
		/// Closes the block of <see cref="Open"/> and opens the one that continues the statement, such as <c>catch</c> or
		/// <c>else</c>, right after the closing brace.
		/// </summary>
		/// <param name="line">The keyword (and condition) of the next block.</param>
		public void Continue(string line)
		{
			depth--;
			Line("}");
			Open(line);
		}

		/// <summary>Indents the following lines one more level, without a brace.</summary>
		public void Indent() => depth++;

		/// <summary>Undoes one <see cref="Indent"/>.</summary>
		public void Unindent() => depth--;

		/// <summary>The text written so far.</summary>
		/// <returns>The source code.</returns>
		public override string ToString() => text.ToString();
	}
}

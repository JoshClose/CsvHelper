	/// <summary>Upper-cases text as .NET's <see cref="string.ToUpperInvariant"/> does.</summary>
	/// <param name="text">The text.</param>
	/// <returns>The text upper-cased.</returns>
	public static string ToUpper(string text)
	{
		var upper = text.ToUpperInvariant().ToCharArray();
		for (var i = 0; i < upper.Length; i++)
		{
			var low = 0;
			var high = Pairs.Length / 2 - 1;
			while (low <= high)
			{
				var middle = (low + high) / 2;
				var c = Pairs[2 * middle];
				if (c == upper[i])
				{
					upper[i] = (char)Pairs[2 * middle + 1];

					break;
				}

				if (c < upper[i])
				{
					low = middle + 1;
				}
				else
				{
					high = middle - 1;
				}
			}
		}

		return new string(upper);
	}
